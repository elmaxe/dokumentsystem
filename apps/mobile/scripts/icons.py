"""Builds the app's icon fonts from Material Symbols Rounded (Apache-2.0), docs/design.md §16.5.

React Native can't read woff2 or pick variable-font axes, so this cuts two static fonts from Google's variable
font: outlined (FILL 0) and filled (FILL 1), both at weight 400, grade 0 and optical size 24, holding only the icons
in icon-names.txt. Icons are drawn by code point, so ligatures aren't needed.

  pip install fonttools
  curl -LO "https://raw.githubusercontent.com/google/material-design-icons/master/variablefont/MaterialSymbolsRounded%5BFILL%2CGRAD%2Copsz%2Cwght%5D.ttf"
  curl -LO "https://raw.githubusercontent.com/google/material-design-icons/master/variablefont/MaterialSymbolsRounded%5BFILL%2CGRAD%2Copsz%2Cwght%5D.codepoints"
  pnpm --filter @dokument/mobile icons -- <the .ttf> <the .codepoints>
"""

import sys
from pathlib import Path

from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

here = Path(__file__).resolve().parent
app = here.parent
font_path, codepoints_path = sys.argv[1], sys.argv[2]

names = [line.strip() for line in (here / "icon-names.txt").read_text().splitlines() if line.strip()]
codepoints = dict(line.split() for line in Path(codepoints_path).read_text().splitlines() if line.strip())
missing = [name for name in names if name not in codepoints]
if missing:
    sys.exit(f"Not in Material Symbols: {', '.join(missing)}")

for fill, file_name, family in [(0, "MaterialSymbolsRounded.ttf", "MaterialSymbolsRounded"), (1, "MaterialSymbolsRoundedFilled.ttf", "MaterialSymbolsRoundedFilled")]:
    font = instantiateVariableFont(TTFont(font_path), {"FILL": fill, "wght": 400, "GRAD": 0, "opsz": 24})
    options = Options()
    options.layout_features = []
    options.name_IDs = ["*"]
    subsetter = Subsetter(options)
    subsetter.populate(unicodes=[int(codepoints[name], 16) for name in names])
    subsetter.subset(font)
    # expo-font registers a font by its file name on Android and by its family name on iOS, so make them agree.
    for record in font["name"].names:
        if record.nameID in (1, 4, 6, 16):
            record.string = family
    font.save(app / "assets" / "fonts" / file_name)

lines = [f'  {name}: 0x{codepoints[name]},' for name in names]
(app / "src" / "ui" / "iconCodepoints.ts").write_text(
    "// Generated by scripts/icons.py from Material Symbols Rounded. Do not edit; add names to scripts/icon-names.txt.\n"
    "export const iconCodepoints = {\n" + "\n".join(lines) + "\n} as const;\n"
)
print(f"icons: {len(names)} icons")
